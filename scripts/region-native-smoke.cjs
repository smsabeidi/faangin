const { app, nativeImage } = require('electron')
const assert = require('node:assert/strict')
const { mkdtempSync, rmSync } = require('node:fs')
const { tmpdir } = require('node:os')
const { join } = require('node:path')
const directory = mkdtempSync(join(tmpdir(), 'faangin-region-native-'))
app.setPath('userData', directory)
app.enableSandbox()
app.whenReady().then(() => {
  app.dock?.hide()
  const width = 8, height = 4, pixels = Buffer.alloc(width * height * 4)
  for (let y = 0; y < height; y++) for (let x = 0; x < width; x++) { const at = (y * width + x) * 4; pixels[at] = x * 20; pixels[at + 1] = y * 40; pixels[at + 2] = 150; pixels[at + 3] = 255 }
  const retina = nativeImage.createFromBitmap(pixels, { width, height, scaleFactor: 2 })
  const png = retina.toPNG(), image = nativeImage.createFromBuffer(png), size = image.getSize()
  assert.equal(size.width, png.readUInt32BE(16)); assert.equal(size.height, png.readUInt32BE(20))
  assert.deepEqual(image.getScaleFactors(), [1])
  const region = { x: 1, y: 1, width: 3, height: 2 }, cropped = image.crop(region), croppedPNG = cropped.toPNG()
  assert.deepEqual(cropped.getSize(), { width: 3, height: 2 })
  assert.equal(croppedPNG.readUInt32BE(16), 3); assert.equal(croppedPNG.readUInt32BE(20), 2)
  const sourceBytes = image.toBitmap(), cropBytes = cropped.toBitmap(), expected = Buffer.concat(Array.from({ length: region.height }, (_, row) => sourceBytes.subarray(((region.y + row) * size.width + region.x) * 4, ((region.y + row) * size.width + region.x + region.width) * 4)))
  assert.deepEqual(cropBytes, expected)
  console.log('Generated Retina bitmap: canonical pixel grid, single scale representation, crop bounds and crop pixels verified. No screen capture or user content accessed.')
  rmSync(directory, { recursive: true, force: true }); app.exit(0)
}).catch(() => { console.error('Generated native region fixture failed.'); rmSync(directory, { recursive: true, force: true }); app.exit(1) })
