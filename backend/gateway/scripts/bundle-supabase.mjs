import { build } from 'esbuild'
import { mkdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
const entry = fileURLToPath(new URL('../src/supabase-edge.ts', import.meta.url))
const destination = fileURLToPath(new URL('../../../supabase/functions/faangin-gateway/', import.meta.url))
const bindings = fileURLToPath(new URL('./edge-node-bindings.mjs', import.meta.url))
const result = await build({ entryPoints: [entry], bundle: true, write: false, format: 'esm', platform: 'node', target: 'es2022', metafile: true,
  // Bundle ws so its CommonJS Buffer/process references get explicit lexical imports too.
  inject: [bindings], external: ['bufferutil', 'utf-8-validate'],
  define: { 'process.env.WS_NO_BUFFER_UTIL': '"1"', 'process.env.WS_NO_UTF_8_VALIDATE': '"1"' },
  banner: { js: 'import { createRequire as edgeCreateRequire } from "node:module"; const require = edgeCreateRequire(import.meta.url);' }
})
if (Object.keys(result.metafile.inputs).some(path => path.includes('firebase-admin'))) throw new Error('Supabase gateway must not bundle Firebase')
const code = result.outputFiles[0].text
await mkdir(destination, { recursive: true })
await writeFile(destination + 'index.ts', '// @ts-nocheck -- generated JavaScript; source is checked by gateway typecheck.\n// Generated by backend/gateway/scripts/bundle-supabase.mjs.\n' + code)
process.stdout.write('Bundled Supabase gateway without Firebase dependencies.\n')
